//! Verification of crypt(3) password hashes as found in `/etc/shadow`.
//!
//! Supported schemes:
//! - `$6$` SHA-512-crypt (Alpine's default)
//! - `$5$` SHA-256-crypt
//! - `$2b$` / `$2y$` / `$2a$` bcrypt
//! - `$y$` yescrypt (Debian/Fedora default; RustCrypto `yescrypt` crate)
//!
//! All implementations are pure Rust, so the binary stays fully static.
//! These functions are CPU-bound: call them from `spawn_blocking`.

use sha_crypt::{PasswordVerifier as _, ShaCrypt};
use yescrypt::Yescrypt;

/// Maximum password length we are willing to hash. SHA-crypt's cost grows with
/// the password length, so this bounds the work an attacker can request.
pub const MAX_PASSWORD_LEN: usize = 1024;

/// A valid SHA-512-crypt hash of a random throwaway password, used to spend the
/// same amount of time on unknown users as on real ones.
const DUMMY_HASH: &str = "$6$3IgAC8eskWK8WQ1Y$GflicZBYDEPrpyCBwpPRlvZ1Wfubq.3s1BFJ4gaDRBefwBYMkagdEvuj0LEs/RcSQu8JNA/MziXp3zRr42UZy.";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Scheme {
    Sha256Crypt,
    Sha512Crypt,
    Bcrypt,
    Yescrypt,
}

#[derive(Debug, thiserror::Error, PartialEq, Eq)]
pub enum PasswordError {
    #[error("unsupported password hash scheme")]
    UnsupportedScheme,
    #[error("malformed password hash")]
    Malformed,
}

pub fn scheme_of(hash: &str) -> Option<Scheme> {
    if hash.starts_with("$6$") {
        Some(Scheme::Sha512Crypt)
    } else if hash.starts_with("$5$") {
        Some(Scheme::Sha256Crypt)
    } else if hash.starts_with("$2b$") || hash.starts_with("$2y$") || hash.starts_with("$2a$") {
        Some(Scheme::Bcrypt)
    } else if hash.starts_with("$y$") {
        Some(Scheme::Yescrypt)
    } else {
        None
    }
}

/// Returns `Ok(true)` if `password` matches `hash`, `Ok(false)` if it does not,
/// and an error if the hash cannot be checked at all.
pub fn verify(password: &str, hash: &str) -> Result<bool, PasswordError> {
    if password.len() > MAX_PASSWORD_LEN {
        return Ok(false);
    }
    let pw = password.as_bytes();
    match scheme_of(hash).ok_or(PasswordError::UnsupportedScheme)? {
        Scheme::Sha256Crypt | Scheme::Sha512Crypt => {
            map_password_hash(ShaCrypt::default().verify_password(pw, hash))
        }
        Scheme::Yescrypt => map_password_hash(Yescrypt::default().verify_password(pw, hash)),
        Scheme::Bcrypt => bcrypt::verify(pw, hash).map_err(|_| PasswordError::Malformed),
    }
}

/// Burns roughly the cost of one SHA-512-crypt verification. Used when the
/// user does not exist so that response timing does not reveal valid names.
pub fn dummy_verify(password: &str) {
    let _ = verify(password, DUMMY_HASH);
}

fn map_password_hash(result: password_hash_result::Result<()>) -> Result<bool, PasswordError> {
    use password_hash_result::Error;
    match result {
        Ok(()) => Ok(true),
        Err(Error::PasswordInvalid) => Ok(false),
        Err(_) => Err(PasswordError::Malformed),
    }
}

/// `sha-crypt` and `yescrypt` both re-export the same `password-hash` crate.
mod password_hash_result {
    pub use sha_crypt::password_hash::{Error, Result};
}

#[cfg(test)]
mod tests {
    use super::*;

    // Reference vectors from the glibc SHA-crypt specification
    // (https://www.akkadia.org/drepper/SHA-crypt.txt).
    const SHA512_HELLO: &str = "$6$saltstring$svn8UoSVapNtMuq1ukKS4tPQd8iKwSMHWjl/O817G3uBnIFNjnQJuesI68u4OTLiBFdcbYEdFCoEOfaS35inz1";
    const SHA512_ROUNDS: &str = "$6$rounds=10000$saltstringsaltst$OW1/O6BYHV6BcXZu8QVeXbDWra3Oeqh0sbHbbMCVNSnCM/UrjmM0Dp8vOuZeHBy/YTBmSK6H9qs/y3RnOaw5v.";
    const SHA256_HELLO: &str = "$5$saltstring$5B8vYYiY.CVt1RlTTf8KbXBH3hsxY/GNooZaBBGWEc5";
    const SHA256_ROUNDS: &str =
        "$5$rounds=10000$saltstringsaltst$3xv.VbSHBb41AL9AvLeujZkZRBAwqFMz2.opqey6IcA";

    // Generated with BusyBox `mkpasswd -m sha512 gotthard` on Alpine 3.24
    // (an implementation independent from the one under test).
    const SHA512_BUSYBOX: &str = "$6$gURxfvOSTsEr5L6B$.4EwcuC0xQo/9IJYPFouQJRu705EAH9FYJwVejS7MDy10cMzFaenI.AYJW1FiuHmQl638hXwxY3XPYE.klXRI/";
    // Generated with BusyBox `mkpasswd -m sha256 gotthard`.
    const SHA256_BUSYBOX: &str = "$5$/kurm6WbdOBIhp8M$RBaxAYhlRbaKLgBjDD4vvEaNK3vWN/63OKm6RtKT9y.";

    // From the bcrypt crate's own interop tests (generated by Python's bcrypt).
    const BCRYPT_2B: &str = "$2b$04$EGdrhbKUv8Oc9vGiXX0HQOxSg445d458Muh7DAHskb6QbtCvdxcie";

    // From the yescrypt reference implementation's TESTS-OK, password
    // "pleaseletmein".
    const YESCRYPT: &str = "$y$j0/$LdJM$k7BXzSDuoGHW56SY3HxROCiA0gWRscZe2aA0q5oHPM0";

    #[test]
    fn detects_schemes() {
        assert_eq!(scheme_of(SHA512_HELLO), Some(Scheme::Sha512Crypt));
        assert_eq!(scheme_of(SHA256_HELLO), Some(Scheme::Sha256Crypt));
        assert_eq!(scheme_of(BCRYPT_2B), Some(Scheme::Bcrypt));
        assert_eq!(scheme_of("$2y$10$abc"), Some(Scheme::Bcrypt));
        assert_eq!(scheme_of(YESCRYPT), Some(Scheme::Yescrypt));
        assert_eq!(scheme_of("$1$md5salt$hash"), None);
        assert_eq!(scheme_of("plaintext"), None);
    }

    #[test]
    fn sha512_crypt() {
        assert_eq!(verify("Hello world!", SHA512_HELLO), Ok(true));
        assert_eq!(verify("Hello world?", SHA512_HELLO), Ok(false));
        assert_eq!(verify("Hello world!", SHA512_ROUNDS), Ok(true));
        assert_eq!(verify("hello world!", SHA512_ROUNDS), Ok(false));
    }

    #[test]
    fn sha256_crypt() {
        assert_eq!(verify("Hello world!", SHA256_HELLO), Ok(true));
        assert_eq!(verify("", SHA256_HELLO), Ok(false));
        assert_eq!(verify("Hello world!", SHA256_ROUNDS), Ok(true));
    }

    #[test]
    fn busybox_generated_hashes() {
        assert_eq!(verify("gotthard", SHA512_BUSYBOX), Ok(true));
        assert_eq!(verify("gotthard!", SHA512_BUSYBOX), Ok(false));
        assert_eq!(verify("gotthard", SHA256_BUSYBOX), Ok(true));
    }

    #[test]
    fn bcrypt() {
        assert_eq!(verify("correctbatteryhorsestapler", BCRYPT_2B), Ok(true));
        assert_eq!(verify("correcthorsebatterystaple", BCRYPT_2B), Ok(false));
        let y = BCRYPT_2B.replacen("$2b$", "$2y$", 1);
        assert_eq!(verify("correctbatteryhorsestapler", &y), Ok(true));
    }

    #[test]
    fn yescrypt() {
        assert_eq!(verify("pleaseletmein", YESCRYPT), Ok(true));
        assert_eq!(verify("pleaseletmeout", YESCRYPT), Ok(false));
    }

    #[test]
    fn rejects_unsupported_and_malformed() {
        assert_eq!(
            verify("x", "$1$abc$def"),
            Err(PasswordError::UnsupportedScheme)
        );
        assert_eq!(verify("x", "!"), Err(PasswordError::UnsupportedScheme));
        assert_eq!(verify("x", "$6$"), Err(PasswordError::Malformed));
        assert_eq!(
            verify("x", "$2b$04$tooshort"),
            Err(PasswordError::Malformed)
        );
        assert_eq!(verify("x", "$y$garbage"), Err(PasswordError::Malformed));
    }

    #[test]
    fn overlong_passwords_never_match() {
        let long = "a".repeat(MAX_PASSWORD_LEN + 1);
        assert_eq!(verify(&long, SHA512_HELLO), Ok(false));
    }

    #[test]
    fn dummy_hash_is_well_formed() {
        // If the dummy hash were malformed the timing equalisation would be a
        // no-op, so make sure it is actually checked.
        assert_eq!(verify("definitely not it", DUMMY_HASH), Ok(false));
    }
}
